"""Regenerate bootstrap summaries, paired Wilcoxon tests, and booktabs LaTeX."""
from __future__ import annotations

import argparse
import csv
import os
import zlib

import numpy as np
from scipy.stats import wilcoxon

from agv_statistical_experiments import CONFIGS, METRICS


LABELS = {
    "makespan": "Makespan (s)", "fleet_back": "Fleet back at parking (s)",
    "tardiness": "Total tardiness (s)", "earliness": "Total earliness (s)",
    "imbalance": "Load imbalance (s)", "wait_total": "Total waiting (s)",
    "wait_max": "Maximum AGV waiting (s)", "alg3_calls": "Algorithm 3 calls",
    "cpu_total_ms": "Total CPU time (ms)", "cpu_ms": "Busiest server CPU time (ms)",
    "wall_ms": "Wall-clock planning time (ms)",
    "max_windows_one_server": "Maximum windows per server",
    "messages": "Messages", "payload_windows": "Payload windows",
}
N_BOOT = 10000


def _read_rows(path):
    with open(path, newline="", encoding="utf-8") as stream:
        return list(csv.DictReader(stream))


def _bootstrap_ci(values, key):
    values = np.asarray(values, dtype=float)
    seed = zlib.crc32(key.encode("utf-8"))
    rng = np.random.default_rng(seed)
    draws = rng.choice(values, size=(N_BOOT, len(values)), replace=True).mean(axis=1)
    return np.quantile(draws, [0.025, 0.975])


def _summary_rows(rows):
    result = []
    regimes = sorted({r["regime"] for r in rows})
    for regime in regimes:
        subset = [r for r in rows if r["regime"] == regime]
        for metric in METRICS:
            all_values = {c: [float(r[metric]) for r in subset if r["config"] == c]
                          for c in CONFIGS}
            for config in CONFIGS:
                vals = all_values[config]
                lo, hi = _bootstrap_ci(vals, f"{regime}:{metric}")
                wins = ties = 0
                for seed in sorted({int(r["seed"]) for r in subset}):
                    by_config = {r["config"]: float(r[metric]) for r in subset if int(r["seed"]) == seed}
                    best = min(by_config.values())
                    winners = [c for c, value in by_config.items()
                               if np.isclose(value, best, rtol=1e-10, atol=1e-9)]
                    if len(winners) == 1 and winners[0] == config:
                        wins += 1
                    elif config in winners:
                        ties += 1
                result.append(dict(regime=regime, metric=metric, config=config, n=len(vals),
                                   mean=float(np.mean(vals)), sd=float(np.std(vals, ddof=1)),
                                   ci95_low=float(lo), ci95_high=float(hi), unique_wins=wins,
                                   tied_best_seeds=ties))
    return result


def _paired_rows(rows):
    result = []
    regimes = sorted({r["regime"] for r in rows})
    for regime in regimes:
        subset = [r for r in rows if r["regime"] == regime]
        for metric in METRICS:
            by_config = {c: {int(r["seed"]): float(r[metric]) for r in subset if r["config"] == c}
                         for c in CONFIGS}
            for ix, first in enumerate(CONFIGS):
                for second in CONFIGS[ix + 1:]:
                    seeds = sorted(set(by_config[first]) & set(by_config[second]))
                    a = np.asarray([by_config[first][s] for s in seeds])
                    b = np.asarray([by_config[second][s] for s in seeds])
                    delta = a - b
                    if np.allclose(delta, 0.0, rtol=0, atol=1e-12):
                        pvalue = 1.0
                    else:
                        pvalue = float(wilcoxon(a, b, alternative="two-sided", zero_method="wilcox",
                                                method="auto").pvalue)
                    result.append(dict(regime=regime, metric=metric, config_a=first,
                                       config_b=second, n=len(seeds),
                                       mean_a_minus_b=float(delta.mean()), p_value=pvalue))
    return result


def _write_csv(path, rows):
    if not rows:
        return
    with open(path, "w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def _latex(summary, paired, regimes):
    out = ["% Generated by generate_latex_tables.py; paired p-values are unadjusted."]
    for regime in regimes:
        ss = [r for r in summary if r["regime"] == regime]
        out += [r"\begin{table*}[t]", r"\centering",
                r"\caption{Per-seed summary for " + regime.replace("_", r"\_") +
                r". Cells show mean (SD), bootstrap 95\% CI, and unique seed wins (lower is better).}",
                r"\label{tab:" + regime.replace("_", "-") + r"}",
                r"\begin{tabular}{l" + "c" * len(CONFIGS) + r"}", r"\toprule",
                "Metric & " + " & ".join(CONFIGS) + r" \\",
                r"\midrule"]
        for metric in METRICS:
            cells = []
            for config in CONFIGS:
                row = next(x for x in ss if x["metric"] == metric and x["config"] == config)
                cells.append(f"{row['mean']:.1f} ({row['sd']:.1f}) [{row['ci95_low']:.1f}, {row['ci95_high']:.1f}]; {row['unique_wins']}")
            out.append(LABELS[metric] + " & " + " & ".join(cells) + r" \\")
        out += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
        pp = [r for r in paired if r["regime"] == regime]
        out += [r"\begin{table*}[t]", r"\centering",
                r"\caption{Paired two-sided Wilcoxon signed-rank tests for " + regime.replace("_", r"\_") +
                r". Difference is config A minus config B; p-values are unadjusted.}",
                r"\label{tab:" + regime.replace("_", "-") + r"-paired}",
                r"\begin{tabular}{llrrr}", r"\toprule",
                r"Metric & Pair & $n$ & Mean difference & $p$ \\",
                r"\midrule"]
        for row in pp:
            pair = row["config_a"] + "--" + row["config_b"]
            out.append(f"{LABELS[row['metric']]} & {pair} & {row['n']} & {row['mean_a_minus_b']:.3f} & {row['p_value']:.6g} " + r"\\")
        out += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    return "\n".join(out)


def generate(raw_path="results_statistics/experiment_raw.csv", outdir="results_statistics"):
    rows = _read_rows(raw_path)
    if not rows or any(r.get("ok", "True").lower() != "true" for r in rows):
        raise ValueError("raw data is empty or contains a non-verified plan")
    summary = _summary_rows(rows)
    paired = _paired_rows(rows)
    _write_csv(os.path.join(outdir, "metric_summary.csv"), summary)
    _write_csv(os.path.join(outdir, "paired_wilcoxon.csv"), paired)
    regimes = sorted({r["regime"] for r in rows})
    tex_path = os.path.join(outdir, "tables.tex")
    with open(tex_path, "w", encoding="utf-8") as stream:
        stream.write(_latex(summary, paired, regimes))
    print(f"Regenerated {len(summary)} summary rows, {len(paired)} paired tests, and {tex_path}")
    return tex_path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--raw", default="results_statistics/experiment_raw.csv")
    parser.add_argument("--outdir", default="results_statistics")
    args = parser.parse_args()
    generate(args.raw, args.outdir)


if __name__ == "__main__":
    main()
